export function getBlogPage(posts, requestedPage = 1) {
  const pageCount = Math.max(1, Math.ceil(posts.length / 9));
  const page = Math.min(
    pageCount,
    Math.max(1, Math.trunc(Number(requestedPage) || 1)),
  );
  return { page, pageCount, posts: posts.slice((page - 1) * 9, page * 9) };
}

export function getBlogPost(slug) {
  return blogPosts.find((post) => post.id === slug);
}

export function filterBlogPosts(posts, query = "", category = "") {
  const term = query.trim().toLocaleLowerCase();
  return posts.filter(
    (post) =>
      (!category || post.category === category) &&
      `${post.title} ${post.category} ${post.excerpt}`
        .toLocaleLowerCase()
        .includes(term),
  );
}

